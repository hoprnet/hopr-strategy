    #[test]
    fn test_tampered_ciphertext_is_skipped() {
        let (store, _dir) = open_temp_store();
        let id = make_id(1);
        let secret = make_secret(0xaa);
        assert!(store.insert(&id, &secret).unwrap());

        // Read, tamper one byte of the stored value, write back directly.
        let mut corrupted = raw_stored_value(&store, &id).expect("should be present");
        corrupted[0] ^= 0xff; // flip all bits in the first byte (nonce)

        // Write the corrupted value directly via raw redb.
        let key = encode_key(&id);
        let write_tx = store.db.begin_write().unwrap();
        {
            let mut table = write_tx.open_table(PIX_RECOVERED_KEYS).unwrap();
            table.insert(key, corrupted).unwrap();
        }
        write_tx.commit().unwrap();

        // iter() must skip the tampered entry.
        let entries = store.iter().unwrap();
        assert!(entries.is_empty(), "tampered entry must be skipped");
    }

    #[test]
    fn test_duplicate_insert_preserves_stored_value() {
        // Same key, re-inserted (duplicate returns false) — `insert` must not overwrite, so
        // the stored value and its nonce stay exactly as the first insert left them.
        let (store, _dir) = open_temp_store();
        let id = make_id(1);
        let secret = make_secret(0xaa);

        store.insert(&id, &secret).unwrap();
        let first = raw_stored_value(&store, &id).expect("first insert");

        // Second insert (duplicate — will NOT overwrite, so the stored value stays)
        store.insert(&id, &secret).unwrap();
        let second = raw_stored_value(&store, &id).expect("second insert");

        assert_eq!(
            first, second,
            "duplicate insert must not overwrite; stored value unchanged"
        );
    }
